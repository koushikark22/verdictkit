"""Labelled synthetic OHLCV for SYNTHETIC_DEMO cases and tests (reel req 5.6, task 8).

The series is generated by a fixed integer recurrence (no randomness, no floats) and is
committed as ``synthetic_ohlcv_v1.csv``; the adapter serves it only if its SHA-256 equals
the pinned digest. It is *not market data* and says nothing about any real instrument.
The core's ``effective_policy`` forbids this source class in every LIVE_EVIDENCE case.
"""
from __future__ import annotations

import hashlib
from datetime import datetime, timezone
from decimal import ROUND_HALF_EVEN, Decimal, localcontext
from importlib import resources

from verdictkit.model import LicenseClass, SourceClass
from verdictkit.plugin import EvidenceRequest

SOURCE_ID = "synthetic-fixture-v1"
INSTRUMENT = "SYNTH-USD"
FILE_NAME = "synthetic_ohlcv_v1.csv"
URI = "fixture://reel-autopsy/synthetic_ohlcv_v1.csv"
HEADER = ("# SYNTHETIC OHLCV - generated test data, NOT market data. "
          "Instrument SYNTH-USD does not exist. reel-autopsy synthetic-fixture-v1")
# Digest of the committed file; tests assert the generator reproduces it byte for byte.
PINNED_SHA256 = "f6fd61d5b9660e81467828d8643f4cf56e81c81ec32de153d2b9ff768d083726"
RIGHTS_NOTE = "Generated test data. Not market data; proves nothing about any real claim."

_START = int(datetime(2025, 1, 1, tzinfo=timezone.utc).timestamp())
_DAYS = 365
_CENT = Decimal("0.01")


def generate() -> bytes:
    """Deterministic daily bars for 2025 (365 bars), canonical CSV bytes."""
    lines = [HEADER, "ts,open,high,low,close,volume"]
    state = 20251119
    close = Decimal("100.00")

    def nxt() -> int:
        nonlocal state
        state = (1103515245 * state + 12345) % 2147483648
        return state

    with localcontext() as ctx:
        ctx.prec = 34
        ctx.rounding = ROUND_HALF_EVEN
        for day in range(_DAYS):
            open_ = close
            # Daily move in basis points: -380 .. +420 (slight upward drift), regime flips
            # every 60 days so that trend-following and holding strategies differ.
            move = Decimal(nxt() % 801 - 380)
            if (day // 60) % 2 == 1:
                move = -move
            close = (open_ * (1 + move / 10000)).quantize(_CENT)
            if close <= 0:
                close = _CENT
            up = Decimal(nxt() % 150) / 10000
            down = Decimal(nxt() % 150) / 10000
            high = (max(open_, close) * (1 + up)).quantize(_CENT)
            low = (min(open_, close) * (1 - down)).quantize(_CENT)
            volume = 1000 + nxt() % 9000
            ts = _START + day * 86400
            lines.append(f"{ts},{open_},{high},{low},{close},{volume}")
    return ("\n".join(lines) + "\n").encode("ascii")


def load() -> bytes:
    data = resources.files("reel_autopsy.sources").joinpath(FILE_NAME).read_bytes()
    if hashlib.sha256(data).hexdigest() != PINNED_SHA256:
        raise ValueError("synthetic fixture does not match its pinned digest")
    return data


class SyntheticFixtureAdapter:
    """Local, network-free adapter. Serves only the pinned synthetic series."""

    source_id = SOURCE_ID
    allowed_hosts: frozenset[str] = frozenset()
    requires_network = False
    source_class = SourceClass.SYNTHETIC_FIXTURE
    license_class = LicenseClass.SYNTHETIC
    rights_note = RIGHTS_NOTE

    def fetch(self, request: EvidenceRequest) -> tuple[bytes, str, str]:
        if request.source_id != SOURCE_ID or request.query.get("instrument") != INSTRUMENT:
            raise ValueError("synthetic adapter serves only the synthetic instrument")
        return load(), URI, "text/csv"
